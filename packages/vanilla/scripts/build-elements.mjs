/**
 * @input Per-component .element.mjs definitions.
 * @output Bundled ESM/classic runtimes and generated web-component markup docs.
 * @position Build and drift-check entry point for Vanilla Astryx elements.
 */

import {mkdir, readdir, readFile, writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';
import {build as esbuild} from 'esbuild';
import {format as formatWithPrettier} from 'prettier';

const packageRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '..',
);
const repoRoot = path.resolve(packageRoot, '../..');
const elementsRoot = path.join(packageRoot, 'elements');
const sourceRoot = path.join(elementsRoot, 'src');
const markupRoot = path.join(packageRoot, 'elements-markup');
const distRoot = path.join(packageRoot, 'dist');
const esmPath = path.join(distRoot, 'astryx-elements.js');
const classicPath = path.join(distRoot, 'astryx-elements.classic.js');

async function loadDefinitions() {
  const files = (await readdir(sourceRoot))
    .filter(file => file.endsWith('.element.mjs'))
    .sort((left, right) => left.localeCompare(right));
  const definitions = [];
  for (const file of files) {
    const module = await import(pathToFileURL(path.join(sourceRoot, file)));
    const definition = module.default;
    if (
      !definition ||
      definition.name !== path.basename(file, '.element.mjs')
    ) {
      throw new Error(`${file} must default-export its same-named definition.`);
    }
    for (const key of [
      'name',
      'tag',
      'attributes',
      'slots',
      'docs',
      'examples',
      'render',
    ]) {
      if (!(key in definition)) throw new Error(`${file} is missing ${key}.`);
    }
    if (!definition.tag.startsWith('ax-')) {
      throw new Error(`${file} tag must start with ax-.`);
    }
    if (!Array.isArray(definition.examples) || definition.examples.length < 2) {
      throw new Error(`${file} must provide at least two examples.`);
    }
    definitions.push({file, definition});
  }
  if (definitions.length === 0)
    throw new Error('No element definitions found.');
  return definitions;
}

function entrySource(definitions) {
  const imports = definitions
    .map(({file}, index) => `import definition${index} from './src/${file}';`)
    .join('\n');
  const names = definitions.map((_definition, index) => `definition${index}`);
  return `${imports}
import {registerElement, registerElements} from './src/runtime.mjs';

const definitions = [${names.join(', ')}];
registerElements(definitions);

export {definitions, registerElement, registerElements};
`;
}

async function bundle(definitions, format) {
  const result = await esbuild({
    stdin: {
      contents: entrySource(definitions),
      resolveDir: elementsRoot,
      sourcefile: 'astryx-elements.entry.mjs',
    },
    bundle: true,
    format,
    globalName: format === 'iife' ? 'AstryxElements' : undefined,
    legalComments: 'inline',
    minify: false,
    platform: 'browser',
    target: ['es2022'],
    write: false,
  });
  return `/* Generated by packages/vanilla/scripts/build-elements.mjs. */\n${result.outputFiles[0].text}`;
}

function attributeValues(spec) {
  if (spec.type === 'boolean') return 'presence';
  if (spec.type === 'enum') return spec.values.join(', ');
  return 'string';
}

function attributeDefault(spec) {
  if (spec.type === 'boolean') return spec.default ? 'present' : 'absent';
  return spec.default === undefined || spec.default === ''
    ? '—'
    : String(spec.default);
}

function renderMarkup(definition) {
  const attributes = Object.entries(definition.attributes)
    .map(
      ([name, spec]) =>
        `${name}: ${attributeValues(spec)} | ${attributeDefault(spec)} | ${spec.description}`,
    )
    .join('\n');
  const slots = Object.entries(definition.slots)
    .map(([name, description]) => `${name}: ${description}`)
    .join('\n');
  const examples = definition.examples
    .map(example => `<!-- variant: ${example.name} -->\n${example.html}`)
    .join('\n\n');
  return `<!-- docs: ${definition.docs} -->
<!-- attributes:
${attributes}
-->
${slots ? `<!-- slots:\n${slots}\n-->\n` : ''}${examples}
`;
}

async function compare(pathname, expected) {
  let actual;
  try {
    actual = await readFile(pathname, 'utf8');
  } catch {
    throw new Error(
      `Missing generated file ${path.relative(repoRoot, pathname)}`,
    );
  }
  if (actual !== expected) {
    throw new Error(
      `Generated file is stale: ${path.relative(repoRoot, pathname)}; run pnpm -F @astryxdesign/vanilla build:elements`,
    );
  }
}

async function main() {
  const definitions = await loadDefinitions();
  const [esm, classic] = await Promise.all([
    bundle(definitions, 'esm'),
    bundle(definitions, 'iife'),
  ]);
  const markup = await Promise.all(
    definitions.map(async ({definition}) => ({
      path: path.join(markupRoot, `${definition.name}.html`),
      content: await formatWithPrettier(renderMarkup(definition), {
        bracketSameLine: true,
        parser: 'html',
      }),
    })),
  );
  const generated = [
    {path: esmPath, content: esm},
    {path: classicPath, content: classic},
    ...markup,
  ];

  if (process.argv.includes('--check')) {
    await Promise.all(generated.map(file => compare(file.path, file.content)));
    console.log(`Element dist and ${markup.length} markup files are current.`);
    return;
  }

  await Promise.all([
    mkdir(distRoot, {recursive: true}),
    mkdir(markupRoot, {recursive: true}),
  ]);
  await Promise.all(generated.map(file => writeFile(file.path, file.content)));
  console.log(
    `Generated ${definitions.length} element definitions, ESM/classic bundles, and CLI markup.`,
  );
}

main().catch(error => {
  console.error(error.message);
  process.exitCode = 1;
});
