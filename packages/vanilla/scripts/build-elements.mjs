import {mkdir, readdir, readFile, writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';
import {build as esbuild} from 'esbuild';
import {JSDOM} from 'jsdom';
import {
  format as formatWithPrettier,
  resolveConfig as resolvePrettierConfig,
} from 'prettier';

const packageRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '..',
);
const repoRoot = path.resolve(packageRoot, '../..');
const elementsRoot = path.join(packageRoot, 'elements');
const sourceRoot = path.join(elementsRoot, 'src');
const markupRoot = path.join(packageRoot, 'elements-markup');
const distRoot = path.join(packageRoot, 'dist');
const indexPath = path.join(sourceRoot, 'index.generated.mjs');
const elementCSSPath = path.join(packageRoot, 'src/elements.generated.css');
const esmPath = path.join(distRoot, 'astryx-elements.js');
const classicPath = path.join(distRoot, 'astryx-elements.classic.js');
const GLOBAL_ATTRIBUTES = new Set([
  'accesskey',
  'autocapitalize',
  'autofocus',
  'class',
  'contenteditable',
  'dir',
  'draggable',
  'enterkeyhint',
  'hidden',
  'id',
  'inert',
  'inputmode',
  'is',
  'itemid',
  'itemprop',
  'itemref',
  'itemscope',
  'itemtype',
  'lang',
  'nonce',
  'part',
  'popover',
  'role',
  'slot',
  'spellcheck',
  'style',
  'tabindex',
  'title',
  'translate',
]);

function kebabToCamel(value) {
  return value.replace(/-([a-z])/g, (_match, letter) => letter.toUpperCase());
}

function normalizeSlot(spec) {
  return typeof spec === 'string' ? {description: spec} : spec;
}

async function loadDefinitions() {
  const files = (await readdir(sourceRoot))
    .filter(file => file.endsWith('.element.mjs'))
    .sort((left, right) => left.localeCompare(right));
  const definitions = [];
  for (const file of files) {
    const module = await import(pathToFileURL(path.join(sourceRoot, file)));
    const definition = module.default;
    if (
      !definition ||
      definition.name !== path.basename(file, '.element.mjs')
    ) {
      throw new Error(`${file} must default-export its same-named definition.`);
    }
    for (const key of [
      'name',
      'tag',
      'attributes',
      'slots',
      'docs',
      'examples',
      'render',
    ]) {
      if (!(key in definition)) throw new Error(`${file} is missing ${key}.`);
    }
    if (!definition.tag.startsWith('ax-')) {
      throw new Error(`${file} tag must start with ax-.`);
    }
    if (!Array.isArray(definition.examples) || definition.examples.length < 2) {
      throw new Error(`${file} must provide at least two examples.`);
    }
    definitions.push({file, definition});
  }
  if (definitions.length === 0)
    throw new Error('No element definitions found.');
  validateDefinitions(definitions.map(item => item.definition));
  return definitions;
}

function entrySource(definitions) {
  const imports = definitions
    .map(({file}, index) => `import definition${index} from './${file}';`)
    .join('\n');
  const names = definitions.map((_definition, index) => `definition${index}`);
  return `// Generated by packages/vanilla/scripts/build-elements.mjs.\n${imports}\nimport {registerElement, registerElements} from './runtime.mjs';\n\nconst definitions = [${names.join(', ')}];\nregisterElements(definitions);\n\nexport {definitions, registerElement, registerElements};\n`;
}

function elementCSS(definitions) {
  const tags = definitions.map(({definition}) => definition.tag).sort();
  const indented = tags.map(tag => `  ${tag}`).join(',\n');
  return `/* Generated by packages/vanilla/scripts/build-elements.mjs. */
/* Custom-element hosts are behavior-only wrappers around native BEM markup. */
:where(
${indented},
  [data-ax-panel-host]
) {
  display: contents;
}

/* Prevent author content from flashing before registration. */
:where(
${indented}
):not(:defined) {
  visibility: hidden;
}

/* The HTML hidden contract must outrank the behavior-only host display. */
:where(
${indented}
)[hidden] {
  display: none !important;
}
`;
}

function mockHelpers(definition) {
  return {
    attr(name) {
      const spec = definition.attributes[name];
      if (spec.type === 'boolean') return false;
      if (spec.default !== undefined) return spec.default;
      if (spec.type === 'enum') return spec.values[0];
      return 'example';
    },
    hasAttribute() {
      return false;
    },
    escape(value) {
      return String(value);
    },
    hasSlot() {
      return true;
    },
    content() {
      return {html: '', slotted: true};
    },
    id(part) {
      return `example-${part}`;
    },
    slot(name = 'default') {
      return `data-ax-slot="${name}"`;
    },
    warn() {},
    authorNodes: new Set(),
  };
}

function isMeaningfulDefaultContent(element) {
  return [...element.childNodes].some(node => {
    if (node.nodeType === 3) return Boolean(node.textContent.trim());
    return node.nodeType === 1 && !node.hasAttribute('slot');
  });
}

function validateDefinitions(definitions) {
  const byTag = new Map(
    definitions.map(definition => [definition.tag, definition]),
  );
  for (const definition of definitions) {
    const rendered = new JSDOM(
      `<!doctype html><body>${definition.render({}, mockHelpers(definition))}</body>`,
    ).window.document.body;
    const regions = new Set(
      [...rendered.querySelectorAll('[data-ax-slot]')].map(element =>
        element.getAttribute('data-ax-slot'),
      ),
    );
    for (const name of Object.keys(definition.slots)) {
      if (!regions.has(name)) {
        throw new Error(
          `${definition.name} declares slot "${name}" without a render region.`,
        );
      }
    }

    for (const example of definition.examples) {
      const body = new JSDOM(`<!doctype html><body>${example.html}</body>`)
        .window.document.body;
      if (!body.querySelector(definition.tag)) {
        throw new Error(
          `${definition.name} example "${example.name}" omits <${definition.tag}>.`,
        );
      }
      for (const element of body.querySelectorAll('*')) {
        if (!element.localName.startsWith('ax-')) continue;
        const targetDefinition = byTag.get(element.localName);
        if (!targetDefinition) {
          throw new Error(
            `${definition.name} example "${example.name}" uses unknown <${element.localName}>.`,
          );
        }
        const aliases = new Map();
        for (const [name, spec] of Object.entries(
          targetDefinition.attributes,
        )) {
          for (const alias of spec.aliases ?? []) aliases.set(alias, name);
        }
        for (const attribute of element.attributes) {
          const canonical = aliases.get(attribute.name) ?? attribute.name;
          const spec = targetDefinition.attributes[canonical];
          if (
            !spec &&
            !GLOBAL_ATTRIBUTES.has(attribute.name) &&
            !attribute.name.startsWith('aria-') &&
            !attribute.name.startsWith('data-') &&
            !/^on[a-z]+$/i.test(attribute.name)
          ) {
            throw new Error(
              `${definition.name} example "${example.name}" gives <${element.localName}> unknown attribute "${attribute.name}".`,
            );
          }
          if (spec?.type === 'enum' && !spec.values.includes(attribute.value)) {
            throw new Error(
              `${definition.name} example "${example.name}" gives ${attribute.name} invalid value "${attribute.value}".`,
            );
          }
        }
        for (const child of element.querySelectorAll(':scope > [slot]')) {
          const slot = child.getAttribute('slot');
          if (!Object.hasOwn(targetDefinition.slots, slot)) {
            throw new Error(
              `${definition.name} example "${example.name}" uses unknown <${element.localName}> slot "${slot}".`,
            );
          }
        }
        for (const requirement of targetDefinition.content ?? []) {
          const hasAttribute = element.hasAttribute(requirement.attribute);
          const hasSlot =
            requirement.slot === 'default'
              ? isMeaningfulDefaultContent(element)
              : Boolean(
                  element.querySelector(
                    `:scope > [slot="${requirement.slot}"]`,
                  ),
                );
          if (requirement.required && !hasAttribute && !hasSlot) {
            throw new Error(
              `${definition.name} example "${example.name}" misses required ${requirement.attribute} or slot="${requirement.slot}" on <${element.localName}>.`,
            );
          }
        }
        for (const [name, rawSlot] of Object.entries(targetDefinition.slots)) {
          const slot = normalizeSlot(rawSlot);
          if (!slot.required) continue;
          const alternative = (targetDefinition.content ?? []).find(
            item => item.slot === name,
          );
          const hasAlternative =
            alternative && element.hasAttribute(alternative.attribute);
          const hasSlot =
            name === 'default'
              ? isMeaningfulDefaultContent(element)
              : Boolean(element.querySelector(`:scope > [slot="${name}"]`));
          if (!hasAlternative && !hasSlot) {
            throw new Error(
              `${definition.name} example "${example.name}" misses required slot "${name}" on <${element.localName}>.`,
            );
          }
        }
      }
    }
  }
}

async function bundle(source, format) {
  const result = await esbuild({
    stdin: {
      contents: source,
      resolveDir: sourceRoot,
      sourcefile: 'index.generated.mjs',
    },
    bundle: true,
    format,
    globalName: format === 'iife' ? 'AstryxElements' : undefined,
    legalComments: 'inline',
    minify: false,
    platform: 'browser',
    target: ['es2022'],
    write: false,
  });
  return `/* Generated by packages/vanilla/scripts/build-elements.mjs. */\n${result.outputFiles[0].text}`;
}

function attributeValues(spec) {
  if (spec.type === 'boolean') return 'boolean';
  if (spec.type === 'enum') return spec.values.join(', ');
  return 'string';
}

function attributeDefault(spec) {
  if (spec.type === 'boolean') return spec.default ? 'present' : 'absent';
  return spec.default === undefined || spec.default === ''
    ? '—'
    : String(spec.default);
}

function propertyNames(attribute, spec) {
  const aliases = spec.aliasProperties?.length
    ? spec.aliasProperties
    : (spec.aliases ?? []).map(kebabToCamel);
  return [spec.property ?? kebabToCamel(attribute), ...aliases];
}

function renderMarkup(definition) {
  const requiredAttributes = new Set(
    (definition.content ?? [])
      .filter(item => item.required)
      .map(item => item.attribute),
  );
  const attributes = Object.entries(definition.attributes)
    .map(([name, spec]) => {
      const aliases = spec.aliases?.length
        ? ` (${spec.aliases.join(', ')})`
        : '';
      const required = requiredAttributes.has(name) ? '*' : '';
      return `${name}${required}${aliases}: ${attributeValues(spec)} | ${attributeDefault(spec)} | ${spec.description}`;
    })
    .join('\n');
  const slots = Object.entries(definition.slots)
    .map(([name, rawSpec]) => {
      const spec = normalizeSlot(rawSpec);
      return `${name}${spec.required ? '*' : ''}: ${spec.description}`;
    })
    .join('\n');
  const events =
    Object.entries(definition.events ?? {})
      .map(([name, description]) => `${name}: ${description}`)
      .join('\n') || 'none';
  const methodEntries = new Map();
  if (definition.control) {
    methodEntries.set('focus()', 'Delegate focus to the inner native control.');
    methodEntries.set(
      'click()',
      'Delegate activation to the inner native control.',
    );
  }
  for (const name of definition.delegates?.methods ?? []) {
    methodEntries.set(
      `${name}()`,
      `Delegate ${name}() to the inner native control.`,
    );
  }
  for (const [name, spec] of Object.entries(definition.methods ?? {})) {
    methodEntries.set(`${name}()`, spec.description);
  }
  const methods =
    [...methodEntries]
      .map(([name, description]) => `${name}: ${description}`)
      .join('\n') || 'none';
  const propertyEntries = Object.entries(definition.attributes).map(
    ([name, spec]) =>
      `${propertyNames(name, spec).join(' / ')}: ${spec.type === 'boolean' ? 'boolean' : 'string'} read/write | ${spec.description}`,
  );
  for (const name of definition.delegates?.properties ?? []) {
    propertyEntries.push(
      `${name}: native read-only | Delegated from the inner native control.`,
    );
  }
  const examples = definition.examples
    .map(example => `<!-- variant: ${example.name} -->\n${example.html}`)
    .join('\n\n');
  return `<!-- docs: ${definition.docs} -->
<!-- attributes:
${attributes}
-->
<!-- slots:
${slots || 'none'}
-->
<!-- events:
${events}
-->
<!-- methods:
${methods}
-->
<!-- properties:
${propertyEntries.join('\n') || 'none'}
-->
${examples}
`;
}

async function compare(pathname, expected) {
  let actual;
  try {
    actual = await readFile(pathname, 'utf8');
  } catch {
    throw new Error(
      `Missing generated file ${path.relative(repoRoot, pathname)}`,
    );
  }
  if (actual !== expected) {
    throw new Error(
      `Generated file is stale: ${path.relative(repoRoot, pathname)}; run pnpm -F @astryxdesign/vanilla build:elements`,
    );
  }
}

async function main() {
  const definitions = await loadDefinitions();
  const prettierConfig = (await resolvePrettierConfig(indexPath)) ?? {};
  const index = await formatWithPrettier(entrySource(definitions), {
    ...prettierConfig,
    parser: 'babel',
  });
  const [esm, classic] = await Promise.all([
    bundle(index, 'esm'),
    bundle(index, 'iife'),
  ]);
  const markup = definitions.map(({definition}) => ({
    path: path.join(markupRoot, `${definition.name}.html`),
    content: renderMarkup(definition),
  }));
  const generated = [
    {path: indexPath, content: index},
    {path: elementCSSPath, content: elementCSS(definitions)},
    {path: esmPath, content: esm},
    {path: classicPath, content: classic},
    ...markup,
  ];

  if (process.argv.includes('--check')) {
    await Promise.all(generated.map(file => compare(file.path, file.content)));
    console.log(
      `Element registries, dist, and ${markup.length} markup files are current.`,
    );
    return;
  }

  await Promise.all([
    mkdir(distRoot, {recursive: true}),
    mkdir(markupRoot, {recursive: true}),
  ]);
  await Promise.all(generated.map(file => writeFile(file.path, file.content)));
  console.log(
    `Generated ${definitions.length} element definitions, registries, ESM/classic bundles, and CLI markup.`,
  );
}

main().catch(error => {
  console.error(error.message);
  process.exitCode = 1;
});
